"""Веса факторов Oracle.

Вес умножается на confidence фактора (0..1) при агрегации сдвигов.
Подбираются эмпирически — стартовые значения консервативные, чтобы
сильно не «разбрасывать» откалиброванные ансамблем вероятности.
"""

from __future__ import annotations

# Базовый максимальный сдвиг: каждый фактор может двинуть вероятность
# на величину до ±MAX_FACTOR_DELTA при confidence=1 и весе=1.
MAX_FACTOR_DELTA = 0.04  # 4 п.п.

# Пользовательские веса факторов (sum можно не нормализовать —
# регулятор применяет общий клампинг сдвига).
DEFAULT_WEIGHTS: dict[str, float] = {
    # Травмы важных игроков → влияют на атаку/защиту
    "injuries": 1.0,
    # Текущая форма команд (W/D/L последние N матчей)
    "form": 1.0,
    # Мотивация по турнирной таблице (борьба за выход / зону вылета)
    "motivation": 0.7,
    # Очные встречи (H2H, профайл «грузов» от профи)
    "h2h_profits": 0.6,
    # Рыночное расхождение: если консенсус букмекеров сильно отличается
    # от ансамбля, применяем небольшой сдвиг в сторону рынка
    "market_drift": 0.5,
}

# Глобальный потолок суммарного сдвига вероятности по одному рынку:
# Oracle не двигает на больше 8 п.п., даже если все факторы тянут в одну
# сторону. Это защищает от перегиба.
MAX_TOTAL_DELTA = 0.08

__all__ = ["DEFAULT_WEIGHTS", "MAX_FACTOR_DELTA", "MAX_TOTAL_DELTA"]
